// Runs before the Nitro server is imported (see the entry in module.ts), so the instrumentations
// can patch modules before the app loads them. Configured with the standard OTEL_* variables.
import type { IncomingMessage } from 'node:http';
import { createRequire } from 'node:module';

import { diag, DiagConsoleLogger } from '@opentelemetry/api';
import { getNodeAutoInstrumentations } from '@opentelemetry/auto-instrumentations-node';
import { diagLogLevelFromString, getBooleanFromEnv, getStringFromEnv } from '@opentelemetry/core';
import { NodeSDK } from '@opentelemetry/sdk-node';
import { register, supportsSyncHooks } from 'import-in-the-middle/register-hooks.mjs';

// @ts-expect-error Generated by the module
import { ignore, publicFiles } from '#nuxt-opentelemetry/options';

import { SDK_KEY } from './sdk';

const isIgnored = (url = '/') => {
    const path = url.split('?')[0]!;
    return (
        publicFiles.has(path) ||
        (ignore as (string | RegExp)[]).some((matcher) =>
            typeof matcher === 'string' ? path.startsWith(matcher) : matcher.test(path)
        )
    );
};

const start = () => {
    const logLevel = getStringFromEnv('OTEL_LOG_LEVEL');
    if (logLevel) diag.setLogger(new DiagConsoleLogger(), { logLevel: diagLogLevelFromString(logLevel) });

    // In-thread ESM hooks, so instrumentations can patch packages the server imports.
    if (supportsSyncHooks()) {
        register();
    } else {
        console.warn(
            `[nuxt-opentelemetry] Node ${process.version} can't run synchronous module hooks, so ESM packages ` +
                "won't be instrumented. Use Node ^22.22.3 or >=24.11.1."
        );
    }

    const sdk = new NodeSDK({
        instrumentations: getNodeAutoInstrumentations({
            '@opentelemetry/instrumentation-http': {
                ignoreIncomingRequestHook: (request: IncomingMessage) => isIgnored(request.url)
            }
        })
    });
    sdk.start();
    // The SDK's exporters load http before the instrumentation's require hook exists, so it only
    // patches http on the next require. Do that now, before Nitro imports http and creates its server.
    const require = createRequire(import.meta.url);
    require('node:http');
    require('node:https');
    (globalThis as Record<symbol, NodeSDK>)[SDK_KEY] = sdk;
};

if (!getBooleanFromEnv('OTEL_SDK_DISABLED')) {
    try {
        start();
    } catch (error) {
        console.error('[nuxt-opentelemetry] The OpenTelemetry SDK failed to start, so nothing is traced.', error);
    }
}
